"""Generate device-owned round screens; no cloud/desktop account data."""
import os
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont

def pack(data):
    out=bytearray();i=0
    while i<len(data):
        n=i+1
        while n<len(data) and data[n]==data[i] and n-i<128:n+=1
        if n-i>=3:out.extend((128+n-i-1,data[i]));i=n;continue
        start=i;i=n
        while i<len(data) and i-start<128:
            n=i+1
            while n<len(data) and data[n]==data[i] and n-i<3:n+=1
            if n-i>=3:break
            i+=min(n-i,128-(i-start))
        out.append(i-start-1);out.extend(data[start:i])
    return out

def main():
    candidates=[os.environ.get('POCKET_FONT',''),'C:/Windows/Fonts/msyh.ttc','/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc']
    path=next((p for p in candidates if p and Path(p).is_file()),None)
    if not path:raise SystemExit('Set POCKET_FONT to a CJK TrueType/OpenType font')
    screens=[('按住话筒','继续按住开始说话','松开取消'),('正在聆听','请说出你的要求','松开结束 · 滑出取消'),('正在发送','录音已保存在设备','请稍候'),('正在识别','正在理解刚才的语音','请稍候'),('录音太短','再按住话筒说一句','可直接重试'),('语音出现问题','请查看设备管理页的诊断','可直接重试'),('已取消','这段录音不会提交','稍后返回'),('达到录音上限','松开话筒，等待上传','最长 20 秒'),('未连接 Wi-Fi','点击设置完成配网','设置'),('正在连接云端','Wi-Fi 已连接','设置'),('需要配置连接','打开管理页面配置服务','设置'),('等待云端画面','连接正在恢复','设置'),('USB 设备管理','用电脑浏览器打开下方地址','旋转调亮度 · 轻触返回'),('Wi-Fi 热点配置','连接下方热点后打开地址','旋转调亮度 · 轻触返回')]
    rows=['#pragma once','// Generated by tools/generate_taiji_ui.py. PackBits 360x360 masks.']
    for index,(title,subtitle,footer) in enumerate(screens):
        im=Image.new('1',(360,360),0);d=ImageDraw.Draw(im)
        for y,value,size in [(30,'CODEX POCKET',14),(90 if index>=12 else 108,title,26),(122 if index>=12 else 154,subtitle,16),(292,footer,14)]:
            if 8<=index<12 and y==292:continue
            f=ImageFont.truetype(path,size);d.text(((360-f.getlength(value))/2,y),value,font=f,fill=1)
        if 8<=index<12:
            f=ImageFont.truetype(path,12);value='转动旋钮或轻触右下设置'
            d.text(((360-f.getlength(value))/2,252),value,font=f,fill=1)
            d.rounded_rectangle((256,274,302,307),8,outline=1)
            d.text((264,282),'设置',font=ImageFont.truetype(path,14),fill=1)
        data=pack(im.tobytes());rows.append('static const uint8_t taijiLocal%d[]={%s};'%(index,','.join(map(str,data))))
    rows.append('static const uint8_t *const taijiLocalStates[]={'+','.join('taijiLocal'+str(i) for i in range(len(screens)))+'};')
    rows.append('static const size_t taijiLocalSizes[]={'+','.join('sizeof(taijiLocal%d)'%i for i in range(len(screens)))+'};')
    (Path(__file__).resolve().parents[1]/'firmware/boards/taiji_knob32/taiji_local_ui.h').write_text('\n'.join(rows)+'\n',encoding='utf-8')
if __name__=='__main__':main()
